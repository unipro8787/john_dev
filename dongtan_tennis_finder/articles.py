def articles_for(city_names: set[str]) -> dict[str, dict]:
    """화면에 나오는 지역만 남긴 글 목록. 남는 섹션이 하나뿐인 글(그 지역 전용 글)은 뺀다."""
    out = {}
    for slug, a in ARTICLES.items():
        sections = []
        for s in a["sections"]:
            if s.get("city") and s["city"] not in city_names:
                continue
            blocks = []
            for b in s["blocks"]:
                if isinstance(b, tuple) and b[0] == "table":
                    rows = [cells for city, cells in b[2] if city in city_names]
                    if rows:
                        blocks.append(("table", b[1], rows))
                else:
                    blocks.append(b)
            if blocks:
                sections.append((s["h"], blocks))
        if len(sections) >= 2:
            out[slug] = {**a, "sections": sections}
    return out
