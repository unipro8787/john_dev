def facility_entries() -> list[dict]:
    """도시·권역 순서대로 시설 한 곳마다 페이지에 필요한 정보를 묶어 돌려준다."""
    out = []
    for city in CITIES:
        for region, names in city["regions"].items():
            for name in names:
                out.append({
                    "name": name,
                    "slug": FACILITY_SLUGS[name],
                    "city": city["name"],
                    "city_slug": CITY_SLUGS[city["name"]],
                    "region": region,
                    "courts": list(city["facilities"][name]),
                    "per_facility": city["source"] == "bucheon",
                    "day_only": bool(city.get("day_only")),
                    "booking_url": city["booking_url"],
                    "booking_name": city["booking_name"],
                    "note": FACILITY_NOTES.get(name),
                    "info": _INFO["facilities"].get(name, {}),
                })
    return out


FACILITY_BY_SLUG = {f["slug"]: f for f in facility_entries()}
